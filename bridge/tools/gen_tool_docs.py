"""Write docs/TOOLS.md, the tool reference, from the server's own tool list.

Run from bridge/:  python tools/gen_tool_docs.py         (writes docs/TOOLS.md)
                   python tools/gen_tool_docs.py --check  (exit code 1 when docs/TOOLS.md is out of date)

The tool list is the one a client sees (BridgeServer.list_tools, every toolset): descriptions, parameter types,
ranges, defaults and descriptions come from the code. Groups, action lines, example calls and the rename table come
from geck_mcp/tool_examples.py. tests/test_tool_docs.py fails when the committed file differs from this output."""
import asyncio
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

OUT = ROOT / 'docs' / 'TOOLS.md'


def listed_tools():
    """{name: Tool} as a client sees them, from a server built on a throwaway project with every toolset."""
    from geck_mcp.config import Project
    from geck_mcp.server import make_server
    from geck_mcp.toolsets import TOOLSETS
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        root = Path(tmp)
        project = Project(project_id='docs', game_root=root / 'game', state_dir=root / 'state',
                          toolsets=list(TOOLSETS))
        (project.game_root / 'Data').mkdir(parents=True)
        tools = asyncio.run(make_server(project).list_tools())
    return {t.name: t for t in tools}


def cell(text):
    """Text safe inside a Markdown table cell."""
    return ' '.join(str(text).split()).replace('|', '\\|')


def type_of(schema):
    """A short type for a JSON schema: string, integer, number[3], object, string | number ..."""
    if 'enum' in schema:
        return 'string' if all(isinstance(v, str) for v in schema['enum']) else 'enum'
    if 'const' in schema:
        return 'string'
    if 'anyOf' in schema:
        names = []
        for option in schema['anyOf']:
            name = type_of(option)
            if name not in names and name != 'null':
                names.append(name)
        return ' \\| '.join(names) or 'any'
    kind = schema.get('type')
    if isinstance(kind, list):
        return ' \\| '.join(k for k in kind if k != 'null')
    if kind == 'array':
        item = type_of(schema.get('items') or {})
        size = schema.get('minItems')
        if size is not None and size == schema.get('maxItems'):
            return '%s[%d]' % (item, size)
        return '%s[]' % item
    return kind or 'any'


def allowed(schema):
    """The values or range a schema allows, in words: 'run, run_all, steps', '1 to 200', 'up to 300 characters'."""
    if 'enum' in schema:
        return ', '.join('`%s`' % v for v in schema['enum'])
    if 'anyOf' in schema:
        parts = [allowed(option) for option in schema['anyOf']]
        return '; '.join(p for p in parts if p)
    out = []
    low = schema.get('minimum', schema.get('exclusiveMinimum'))
    high = schema.get('maximum', schema.get('exclusiveMaximum'))
    if low is not None or high is not None:
        above = 'above ' if 'exclusiveMinimum' in schema else ''
        below = 'below ' if 'exclusiveMaximum' in schema else ''
        if low is not None and high is not None:
            out.append('%s%s to %s%s' % (above, low, below, high) if not (above or below) else
                       '%s%s, %s%s' % (above, low, below or 'up to ', high))
        elif low is not None:
            out.append('%s%s or more' % (above, low) if not above else 'above %s' % low)
        else:
            out.append('%s%s' % (below or 'up to ', high))
    if schema.get('maxLength'):
        out.append('up to %d characters' % schema['maxLength'])
    if schema.get('pattern'):
        out.append('pattern `%s`' % schema['pattern'])
    if schema.get('type') == 'array':
        inner = allowed(schema.get('items') or {})
        if inner:
            out.append('each: ' + inner)
        if schema.get('maxItems') and schema.get('minItems') != schema.get('maxItems'):
            out.append('at most %d items' % schema['maxItems'])
    return ', '.join(out)


def default_of(name, schema, required):
    if name in required:
        return 'required'
    if 'default' in schema:
        return '`%s`' % json.dumps(schema['default'])
    return ''


def first_paragraph(text):
    return ' '.join((text or '').split())


def render():
    from geck_mcp.fnv_guide import tool_table
    from geck_mcp.tool_examples import ACTIONS, EXAMPLES, GROUPS, RENAMED_TOOLS
    tools = listed_tools()
    table = tool_table()
    lines = ['# Tool reference', '',
             'Generated by `bridge/tools/gen_tool_docs.py` from the server\'s own tool list; do not edit by hand. '
             'Run `python tools/gen_tool_docs.py` from `bridge/` after changing a tool. %d tools in %d groups.'
             % (len(tools), len(GROUPS)), '',
             'Every tool answers with the same envelope: `ok`, `outcome`, `data` (the answer), and on failure '
             '`error` with a `code`, a `message` and a `recovery` line that says what to do next. **Kinds:** a read '
             'tool changes nothing; an act tool changes the running game, needs `fnv.engine_control` set to `full` '
             'and is journaled (`fnv_journal`, `fnv_undo`); a control tool changes files or starts and stops the game. '
             'A tool with several kinds takes the strongest kind of its actions.', '',
             'Where to start: [docs/README.md](README.md). How the tools reach the game: '
             '[FNV-LIVE-TOOLS.md](FNV-LIVE-TOOLS.md).', '', '## Groups', '']
    for title, summary, names in GROUPS:
        lines.append('- [%s](#%s): %s' % (title, anchor(title), summary))
    lines.append('- [Renamed tools](#renamed-tools)')
    lines.append('')
    for title, summary, names in GROUPS:
        lines += ['## %s' % title, '', summary, '']
        lines.append(' · '.join('[`%s`](#%s)' % (n, n) for n in names))
        lines.append('')
        for name in names:
            lines += tool_section(name, tools[name], table[name], ACTIONS.get(name), EXAMPLES[name])
    lines += ['## Renamed tools', '',
              'Tools that did the same job became one tool with actions. The old names no longer work.', '',
              '| Old name | Use now |', '| --- | --- |']
    for old, new in RENAMED_TOOLS.items():
        lines.append('| `%s` | `%s` |' % (old, cell(new)))
    lines.append('')
    return '\n'.join(lines)


def anchor(title):
    """GitHub's heading anchor."""
    out = ''.join(c for c in title.lower() if c.isalnum() or c in ' -_')
    return out.replace(' ', '-')


def tool_section(name, tool, row, actions, example):
    schema = tool.input_schema or {}
    props = schema.get('properties') or {}
    required = set(schema.get('required') or [])
    out = ['### %s' % name, '',
           '**Kind:** %s · **Toolset:** %s' % (row['kind'], row['toolset']), '',
           first_paragraph(tool.description), '']
    if actions:
        out.append('**Actions:**')
        out.append('')
        for action, line in actions.items():
            default = ' (default)' if (props.get('action') or {}).get('default') == action else ''
            out.append('- `%s`%s: %s' % (action, default, line))
        out.append('')
    if props:
        out += ['| Parameter | Type | Allowed | Default | What it is |', '| --- | --- | --- | --- | --- |']
        for param, p in props.items():
            out.append('| `%s` | %s | %s | %s | %s |' % (param, type_of(p), cell(allowed(p)),
                                                        default_of(param, p, required), cell(p.get('description', ''))))
        out.append('')
    else:
        out += ['No parameters.', '']
    out += ['Example:', '', '```json', json.dumps({'tool': name, 'arguments': example}), '```', '']
    return out


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if '--check' in argv:
        current = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        if current != text:
            sys.stderr.write('docs/TOOLS.md is out of date: run python tools/gen_tool_docs.py\n')
            return 1
        return 0
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print('wrote %s (%d characters)' % (OUT, len(text)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
